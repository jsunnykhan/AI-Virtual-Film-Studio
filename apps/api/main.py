@app.get("/studio/projects")
def list_studio_projects():
    """Lists all projects with full production records."""
    projects_dir = Path(settings.media_output_dir) / "projects"
    projects = []
    if projects_dir.exists():
        for f in sorted(projects_dir.glob("*.json"), key=lambda p: p.stat().st_mtime, reverse=True):
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
                concept_out = data.get("concept", {}).get("output", {})
                idea_out = data.get("idea", {}).get("output", {})
                ep_out = data.get("final_decision", {}).get("output", {})
                projects.append({
                    "project_id": f.stem,
                    "title": concept_out.get("title") or idea_out.get("title") or ep_out.get("title", f.stem),
                    "format": data.get("format", "movie"),
                    "status": data.get("status", "completed"),
                    "modified_at": f.stat().st_mtime,
                })
            except Exception:
                continue
    return {"total": len(projects), "projects": projects}


@app.get("/studio/projects/{project_id}")
def get_studio_project_details(project_id: str):
    """Returns the complete 24-agent output package and workflow state for a project."""
    engine = get_autonomous_studio_engine()
    data = engine.get_project(project_id)
    if not data:
        p = Path(settings.media_output_dir) / "projects" / f"{project_id}.json"
        if p.exists():
            try:
                data = json.loads(p.read_text(encoding="utf-8"))
            except Exception as exc:
                raise HTTPException(status_code=500, detail=str(exc))
    if not data:
        raise HTTPException(status_code=404, detail=f"Project {project_id} not found")
    return {"project_id": project_id, "state": data}


