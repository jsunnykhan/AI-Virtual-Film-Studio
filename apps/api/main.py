def get_creative_catalog_endpoint():
    """Returns all autonomously and on-demand generated creative concepts."""
    path = Path("output") / "creative_concepts.json"
    concepts = []
    if path.exists():
        try:
            concepts = json.loads(path.read_text(encoding="utf-8"))
        except Exception as exc:
            logger.warning(f"Error reading creative concepts catalog: {exc}")
    return {
        "total_concepts": len(concepts),
        "catalog": concepts,
    }


@app.get("/workflows/creative/latest")
@app.get("/creative/latest")
def get_latest_creative_concept():
    """Returns the most recent creative concept produced."""
    path = Path("output") / "creative_concepts.json"
    if path.exists():
        try:
            concepts = json.loads(path.read_text(encoding="utf-8"))
            if concepts:
                return {"latest_concept": concepts[-1]}
        except Exception as exc:
            logger.warning(f"Error reading latest creative concept: {exc}")
    return {"latest_concept": None, "message": "No creative concepts generated yet."}


