@asynccontextmanager
async def lifespan(_: FastAPI) -> AsyncIterator[None]:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    )
    configure_tracing()
    logger.info("Initializing database and vector extensions...")
    await init_db()

    # Automatically launch the 24/7 continuous autonomous production loop
    studio_engine = get_autonomous_studio_engine()
    if settings.autonomous_studio_enabled:
        logger.info("\n" + "=" * 65)
        logger.info("🎬 AI MOVIE STUDIO ONLINE — 24/7 AUTONOMOUS AGENT LOOP ACTIVE")
        logger.info("Agents will continuously generate, direct, render, and assemble films.")
        logger.info("=" * 65 + "\n")
        studio_engine.start()

    yield

    # Clean shutdown
    logger.info("Shutting down autonomous studio and closing connection pools...")
    studio_engine.stop()
    await close_pool()


