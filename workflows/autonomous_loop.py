from __future__ import annotations

import asyncio
from datetime import datetime, timezone
import json
import logging
from pathlib import Path
from typing import Any
from uuid import uuid4

from shared.core.settings import Settings
from workflows.movie_workflow import build_movie_workflow
from workflows.creative_workflow import save_creative_concept

logger = logging.getLogger("autonomous_studio")
settings = Settings()


class AutonomousStudioEngine:
    """
    24/7 Autonomous Virtual Film Studio Engine.
    Runs continuously without requiring user input:
    1. Autonomously conceives new animated movie or series ideas.
    2. Guides the concept through all 24 specialized studio agents.
    3. Renders shots via ComfyUI API and downloads the media.
    4. Merges/assembles shots into 5-minute scenes and full movies with FFmpeg.
    5. Clears rights & continuity, saves to the studio catalog, and immediately begins the next film.
    """

    def __init__(self) -> None:
        self.is_running: bool = False
        self.is_paused: bool = False
        self._task: asyncio.Task[None] | None = None
        self.current_project_id: str | None = None
        self.current_stage: str = "idle"
        self.current_project_title: str | None = None
        self.cycle_count: int = 0
        self.successful_productions: int = 0
        self.failed_productions: int = 0
        self.started_at: datetime | None = None
        self.last_completed_at: datetime | None = None
        self.last_error: str | None = None
        self.catalog_path = Path(settings.media_output_dir) / "studio_catalog.json"
        self.catalog_path.parent.mkdir(parents=True, exist_ok=True)

    def get_status(self) -> dict[str, Any]:
        """Return real-time operational status of the 24/7 studio."""
        return {
            "studio_active_24_7": self.is_running,
            "paused": self.is_paused,
            "current_project_id": self.current_project_id,
            "current_project_title": self.current_project_title,
            "current_stage": self.current_stage,
            "cycle_count": self.cycle_count,
            "successful_productions": self.successful_productions,
            "failed_productions": self.failed_productions,
            "started_at": self.started_at.isoformat() if self.started_at else None,
            "last_completed_at": self.last_completed_at.isoformat() if self.last_completed_at else None,
            "last_error": self.last_error,
            "catalog_path": str(self.catalog_path),
        }

    def get_catalog(self) -> list[dict[str, Any]]:
        """Return the list of all movies/series generated by the autonomous studio."""
        if self.catalog_path.exists():
            try:
                return json.loads(self.catalog_path.read_text(encoding="utf-8"))
            except Exception as exc:
                logger.warning(f"Error reading studio catalog: {exc}")
        return []

    def _record_to_catalog(self, entry: dict[str, Any]) -> None:
        """Persist a completed movie production record to the studio catalog."""
        catalog = self.get_catalog()
        catalog.append(entry)
        try:
            self.catalog_path.write_text(json.dumps(catalog, indent=2), encoding="utf-8")
        except Exception as exc:
            logger.error(f"Failed to write to studio catalog: {exc}")

    def start(self) -> None:
        """Start the autonomous 24/7 studio background loop."""
        if self.is_running:
            logger.info("Autonomous studio is already running.")
            return

        self.is_running = True
        self.is_paused = False
        self.started_at = datetime.now(timezone.utc)
        self._task = asyncio.create_task(self._run_forever())
        logger.info("🎬 Autonomous 24/7 AI Movie Studio STARTED. Operating continuously without human intervention.")

    def pause(self) -> None:
        """Pause the loop between productions."""
        self.is_paused = True
        logger.info("⏸️ Autonomous studio PAUSED. Current project will finish, but no new projects will start.")

    def resume(self) -> None:
        """Resume the loop."""
        self.is_paused = False
        logger.info("▶️ Autonomous studio RESUMED.")

    def stop(self) -> None:
        """Stop the autonomous studio background task."""
        self.is_running = False
        if self._task and not self._task.done():
            self._task.cancel()
        logger.info("🛑 Autonomous studio STOPPED.")

    def restart(self) -> None:
        """Restart the autonomous studio loop."""
        logger.info("🔄 Restarting autonomous studio...")
        self.stop()
        self.start()

    def get_project(self, project_id: str) -> dict[str, Any] | None:
        """Retrieve full 24-agent output package for a given project ID."""
        projects_dir = Path(settings.media_output_dir) / "projects"
        project_file = projects_dir / f"{project_id}.json"
        if project_file.exists():
            try:
                return json.loads(project_file.read_text(encoding="utf-8"))
            except Exception as exc:
                logger.warning(f"Error reading project {project_id}: {exc}")
        return None

    async def _run_forever(self) -> None:
        """Continuous production loop."""
        while self.is_running:
            if self.is_paused:
                self.current_stage = "paused"
                await asyncio.sleep(5)
                continue

            self.cycle_count += 1
            timestamp_str = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
            project_id = f"auto_{timestamp_str}_{uuid4().hex[:6]}"
            self.current_project_id = project_id
            self.current_stage = "initializing_new_production"
            self.current_project_title = f"Autonomous Project #{self.cycle_count}"

            logger.info(
                f"\n{'='*70}\n"
                f"🚀 [CYCLE {self.cycle_count}] Launching Autonomous Production: {project_id}\n"
                f"{'='*70}"
            )

            cycle_start = datetime.now(timezone.utc)

            initial_state = {
                "project_id": project_id,
                "user_request": (
                    "Autonomous 24/7 AI Film Studio: Continuously generate a unique, original animated "
                    "film or episodic series concept without human prompting. You autonomously decide "
                    "the format and runtime (whether a short film, a 90-minute feature, a 120-minute drama, "
                    "or an epic 200+ minute saga). Fully develop the narrative, characters, and world, "
                    "render scenes through ComfyUI, and merge into a finished master video."
                ),
                "format": "movie",
                "target_duration_minutes": None,  # Decided dynamically by the AI agents (no hardcoding)
                "iteration": 0,
                "max_iterations": 3,
                "status": "autonomous_production_started",
            }

            try:
                self.current_stage = "executing_full_movie_workflow"
                workflow = build_movie_workflow()

                # Execute all 24 agents + ComfyUI rendering + FFmpeg assembly
                final_state = await workflow.ainvoke(
                    initial_state,
                    config={"recursion_limit": 50},
                )

                # Extract production metadata
                concept_output = final_state.get("concept", {}).get("output", {})
                title = concept_output.get("title") or final_state.get("idea", {}).get("output", {}).get("title", f"Film #{self.cycle_count}")
                self.current_project_title = title

                assembled_scene = final_state.get("assembled_scene_path")
                final_movie = final_state.get("final_movie_path")
                clearance = final_state.get("rights_clearance", {}).get("output", {})

                # Dynamic runtime decided by the AI agents
                actual_duration = (
                    final_state.get("target_duration_minutes")
                    or final_state.get("production_plan", {}).get("output", {}).get("target_runtime_minutes")
                    or final_state.get("final_decision", {}).get("output", {}).get("duration")
                )

                production_record = {
                    "cycle_number": self.cycle_count,
                    "project_id": project_id,
                    "title": title,
                    "format": final_state.get("format", "movie"),
                    "genre": concept_output.get("genre") or final_state.get("final_decision", {}).get("output", {}).get("genre", []),
                    "logline": concept_output.get("logline") or final_state.get("idea", {}).get("output", {}).get("premise", ""),
                    "runtime_decided_by_ai": actual_duration,
                    "creative_workflow": "completed",
                    "scene_video_path": assembled_scene,
                    "final_movie_path": final_movie,
                    "clearance_verdict": clearance.get("final_clearance_verdict", "cleared_for_worldwide_distribution"),
                    "produced_at": datetime.now(timezone.utc).isoformat(),
                    "total_render_duration_seconds": (datetime.now(timezone.utc) - cycle_start).total_seconds(),
                    "status": "completed",
                }

                # Save creative concept deliverables to creative catalog
                try:
                    save_creative_concept(final_state)
                except Exception as exc:
                    logger.warning(f"Could not persist creative concept record: {exc}")

                # Save full 24-agent output package to individual project file
                try:
                    projects_dir = Path(settings.media_output_dir) / "projects"
                    projects_dir.mkdir(parents=True, exist_ok=True)
                    project_file = projects_dir / f"{project_id}.json"
                    project_file.write_text(json.dumps(final_state, indent=2, default=str), encoding="utf-8")
                except Exception as exc:
                    logger.warning(f"Could not persist full project record: {exc}")

                self._record_to_catalog(production_record)
                self.successful_productions += 1
                self.last_completed_at = datetime.now(timezone.utc)
                self.current_stage = "production_completed"

                logger.info(
                    f"\n{'='*70}\n"
                    f"✅ [CYCLE {self.cycle_count} COMPLETE] Finished: '{title}' ({project_id})\n"
                    f"🎬 Assembled Scene: {assembled_scene}\n"
                    f"🎞️ Master Movie: {final_movie}\n"
                    f"{'='*70}"
                )

            except asyncio.CancelledError:
                logger.info("Autonomous studio task cancelled.")
                break

            except Exception as exc:
                self.failed_productions += 1
                self.last_error = str(exc)
                logger.error(f"❌ [CYCLE {self.cycle_count} FAILED] Project {project_id} encountered error: {exc}", exc_info=True)
                self.current_stage = f"error_recovered: {exc}"

            # Cooldown interval before starting the next production
            cooldown = max(1, settings.autonomous_loop_interval_seconds)
            self.current_stage = f"cooling_down_{cooldown}s_before_next_movie"
            logger.info(f"⏳ Next autonomous production starts in {cooldown} seconds...")
            await asyncio.sleep(cooldown)


# Global singleton instance
_engine: AutonomousStudioEngine | None = None


def get_autonomous_studio_engine() -> AutonomousStudioEngine:
    global _engine
    if _engine is None:
        _engine = AutonomousStudioEngine()
    return _engine
